LOADI R2, 0x6000
LOADI R3, 0x4E19
LOADI R4, 2
LOADI R5, 0x8000
LOADI R6, fill

fill:
STORE [R2], R3
ADD R2, R2, R4
CMP R2, R5
JLT R6

LOADI R2, 16
LOADI R3, 30
LOADI R4, 0xFEC4
LOADI R6, plot
CALL R6

plot:
LOADI R5, 6
SHL R5, R3, R5
ADD R5, R5, R2
ADD R5, R5, R5
LOADI R6, 0x6000
ADD R5, R5, R6
STORE [R5], R4
RET

HALT