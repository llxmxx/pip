LOADI R0, 32
LOADI R1, 32
LOADI R2, 0
LOADI R3, 0

step:
LOADI R6, celladdr
CALL R6
LOAD R5, [R4]

LOADI R6, white
JZ R6, R5

LOADI R5, 0
STORE [R4], R5
LOADI R5, 3
ADD R2, R2, R5
LOADI R6, turned
JMP R6

white:
LOADI R5, 0x7FF
STORE [R4], R5
LOADI R5, 1
ADD R2, R2, R5

turned:
LOADI R5, 3
AND R2, R2, R5

LOADI R5, 0
CMP R2, R5
LOADI R6, up
JEQ R6
LOADI R5, 1
CMP R2, R5
LOADI R6, right
JEQ R6
LOADI R5, 2
CMP R2, R5
LOADI R6, down
JEQ R6

LOADI R5, 1
SUB R0, R0, R5
LOADI R6, moved
JMP R6

up:
LOADI R5, 1
SUB R1, R1, R5
LOADI R6, moved
JMP R6

right:
LOADI R5, 1
ADD R0, R0, R5
LOADI R6, moved
JMP R6

down:
LOADI R5, 1
ADD R1, R1, R5
LOADI R6, moved
JMP R6

moved:
LOADI R5, 63
AND R0, R0, R5
AND R1, R1, R5

LOADI R5, 1
ADD R3, R3, R5
LOADI R5, 11000
CMP R3, R5
LOADI R6, step
JLT R6

PRINT R0
PRINT R1
HALT

celladdr:
LOADI R5, 6
SHL R4, R1, R5
ADD R4, R4, R0
LOADI R5, 1
SHL R4, R4, R5
LOADI R5, 0x6000
ADD R4, R4, R5
RET